from pack_fixture_case import PackFixtureCase
import copy
import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from storymotion import __version__
from storymotion import account_packs
from storymotion.account_packs import ACCOUNTS, catalog, load_pack, sample_brief
from storymotion.dashboard import Dashboard
from storymotion.engine import Engine
from storymotion.provenance import execution_provenance
from storymotion.security import WorkflowError

ROOT = Path(__file__).resolve().parents[1]


class CustomerPackTests(PackFixtureCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        shutil.copytree(Path(__file__).parent / 'fixtures/pack-registry/accountpacks/neutral', self.root / 'accountpacks/neutral')
        self.folder = self.root / 'work/accountpacks'
        self.folder.mkdir(parents=True)
        self.scope = patch.object(account_packs, 'ROOT', self.root)
        self.scope.start()
        self.addCleanup(self.scope.stop)
        self.addCleanup(self.temp.cleanup)

    def buyer(self, source='sample-flow', ident='buyer-demo'):
        pack = load_pack(source)
        pack['id'] = ident
        pack['display_name'] = 'Buyer demonstration'
        pack['profile']['id'] = ident
        pack['fixture']['brand'] = ident
        (self.folder / (ident + '.json')).write_text(json.dumps(pack))
        return pack

    def test_new_json_is_selected_and_prepared_without_code_changes(self):
        pack = self.buyer()
        dashboard = Dashboard(self.root / 'session')
        self.addCleanup(dashboard.clear_keys)
        self.assertIn(pack['id'], [p['id'] for p in dashboard.catalog['accounts']])
        template = dashboard.template(pack['id'], 'account-video')
        video = template['template']['video']
        self.assertEqual(video['brand'], pack['id'])
        job = dashboard.enqueue({'account': pack['id'], 'format': 'account-video', 'title': video['title'],
                                 'brief': video['brief'], 'content': video['script'], 'caption': video['caption'],
                                 'provider': 'local', 'model': 'manual', 'task': 'text', 'template_revision': 0})
        self.assertEqual(job['payload']['account']['id'], pack['id'])
        brief = self.root / 'brief.json'
        brief.write_text(json.dumps(video))
        for renderer in ('hyperframes', 'remotion'):
            engine = Engine(self.root / renderer)
            self.addCleanup(lambda e=engine: e._store.db.close() if e._store else None)
            key = engine.create(brief, render_engine=renderer)['job']
            engine.run(key, 'prepare')
            output = engine.directory(key)
            self.assertIn('data-visual-family="approval-conveyor"', (output / 'index.html').read_text())
            self.assertIn('Generated by StoryMotion ' + __version__, (output / 'BRIEF.md').read_text())
            self.assertFalse((output / 'master.mp4').exists())

    def test_huge_integer_nested_and_good_pack_coexist(self):
        self.buyer()
        for name, raw in [('integer', '{"number":' + '9' * 5000 + '}'),
                          ('nested', '[' * 2500 + '0' + ']' * 2500),
                          ('syntax', '{bad json'), ('utf8', b'\xff')]:
            path = self.folder / (name + '.json')
            path.write_bytes(raw if isinstance(raw, bytes) else raw.encode())
        packs, errors = catalog()
        self.assertIn('buyer-demo', packs)
        self.assertEqual(len(errors), 4)
        self.assertTrue(all(e['code'] == 'CUSTOMER_PROFILE_MALFORMED' for e in errors))
        self.assertIn('buyer-demo', ACCOUNTS)
        dashboard = Dashboard(self.root / 'session')
        self.addCleanup(dashboard.clear_keys)
        self.assertEqual(len(dashboard.catalog['account_pack_errors']), 4)
        self.assertEqual(dashboard.template('buyer-demo', 'account-video')['template']['video']['brand'], 'buyer-demo')

    def test_identifiers_duplicates_symlinks_and_capabilities_fail_closed(self):
        pack = self.buyer()
        for account in ('../outside', '/absolute', 'buyer%2fdemo', '', None):
            with self.subTest(account=account), self.assertRaises(WorkflowError):
                load_pack(account)
        (self.folder / 'sample-flow.json').write_text(json.dumps(load_pack('sample-flow')))
        (self.folder / 'linked.json').symlink_to(self.folder / 'buyer-demo.json')
        pack['capabilities']['manual_scene_kinds'] = ['execute-script']
        (self.folder / 'buyer-demo.json').write_text(json.dumps(pack))
        packs, errors = catalog()
        self.assertNotIn('buyer-demo', packs)
        self.assertEqual(len(errors), 3)
        self.assertIn('CUSTOMER_PROFILE_DUPLICATE', {e['code'] for e in errors})

    def test_pack_change_invalidates_execution_fingerprint(self):
        pack = self.buyer()
        before = execution_provenance()['fingerprint']
        pack['display_name'] = 'Changed buyer title'
        (self.folder / 'buyer-demo.json').write_text(json.dumps(pack))
        self.assertNotEqual(before, execution_provenance()['fingerprint'])

    @unittest.skipUnless(shutil.which('node'), 'Node required for offline DOM selection')
    def test_new_json_dashboard_selection_uses_declared_capabilities(self):
        from test_compact_ui import BOOT, JS, MARKUP
        self.buyer()
        dashboard = Dashboard(self.root / 'session')
        self.addCleanup(dashboard.clear_keys)
        providers = json.loads((ROOT / 'catalog/providers.json').read_text())['providers']
        body = """
        context.fetch=async path=>({ok:true,json:async()=>context.template});
        context.template=TEMPLATE;
        await run("selectAccount('buyer-demo')");
        assert.equal(run('state.account.id'),'buyer-demo');
        assert.equal(run('topicName(state.account)'),'Buyer demonstration');
        assert.equal(run("packCapability(state.account,'rig_mode')"),'inset');
        assert.equal(run('packSerial(state.account)'),false);
        """.replace('TEMPLATE', json.dumps(dashboard.template('buyer-demo', 'account-video')))
        script = BOOT.replace('STRUCTURE', json.dumps(MARKUP.nodes)).replace('SOURCE', json.dumps(JS))
        script = script.replace('CATALOG', json.dumps(dashboard.catalog)).replace('PROVIDERS', json.dumps(providers)).replace('BODY', body)
        result = subprocess.run(['node'], input=script, text=True, capture_output=True, timeout=15)
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == '__main__':
    unittest.main()
